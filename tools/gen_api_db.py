#!/usr/bin/env python3
"""Generate qiling/unpack/api_db.inc: an export-name -> owning-DLL table.

Why this exists
---------------
Recovering a payload's imports from a dump often yields NAMES without their DLL
(the stub's rebuilt tables keep the names but drop the descriptor's Name field, so
"the DLL string nearest before the table" - taote's only attribution source - finds
nothing). PLAN_UNPACK §0.17ae measured that this single missing asset blocks every
import near-miss: PEtite's 12 CEP-correct rows, MEW's 4, WinUpack's 3, plus the
ordinal-only rows (mew_Bginfo 861 pairs = 808 named + 53 ordinals).

Provenance
----------
The table is built from the host's mingw-w64 IMPORT LIBRARIES, i.e. an SDK export
database (libkernel32.a lists what kernel32.dll exports, and so on). It is NOT
derived from the corpus's unpacked originals - that would be ground truth and would
make the measurement circular - so using it is the same kind of host knowledge the
reference's `host_dll_has_export` uses on Windows (where it reads the real
System32 DLLs). On Linux there are no real DLLs; these .a files are the equivalent.

Usage
-----
    tools/gen_api_db.py --libdir /usr/i686-w64-mingw32/lib \
                        --out qiling/unpack/api_db.inc

The output is committed so a build without mingw-w64 still works. Regenerate only
when the mingw version changes; the file is a sorted "name<TAB>dll<LF>" blob.
"""
from __future__ import annotations

import argparse
import glob
import os
import re
import subprocess
import sys

# Pseudo-libraries and API-set forwarders: they re-export other DLLs' names under
# synthetic stems (onecoreuap_apiset alone carries 19k forwarded names), which
# would attribute a kernel32 function to a DLL no program ever imports from.
SKIP_SUBSTRINGS = (
    "apiset", "headless", "windowsapp", "onecore", "mincore", "ucrtbased",
    "api-ms", "ext-ms", "downlevel", "uuid", "ksuser", "oldnames", "icu",
    "wsmsvc", "ucrtapp", "vcruntime", "msvcp", "msvcr", "concrt",
)

# A few names exist in several libraries. Attribution prefers the library the dump
# itself names, but the table needs one default, so the classic system DLLs win.
PRIORITY = (
    "kernel32", "user32", "gdi32", "advapi32", "shell32", "ole32", "oleaut32",
    "comctl32", "comdlg32", "version", "ws2_32", "winmm", "shlwapi", "imm32",
    "netapi32", "crypt32", "psapi", "iphlpapi", "msvcrt", "setupapi", "urlmon",
    "wininet", "uxtheme", "dbghelp", "wintrust", "secur32", "mpr", "ntdll",
)

SYMBOL_RE = re.compile(r"\b[TI]\s+_?([A-Za-z_][A-Za-z0-9_@?$]*)$")


def library_exports(path: str) -> set[str]:
    """The export names of one mingw import library, undecorated.

    x86 import symbols are stdcall-decorated (`_lstrlenW@4`); the dump stores the
    undecorated name, so strip the leading underscore and the `@N` byte count.
    `__imp_foo` is the IAT-slot alias of `foo`, not another export.
    """
    out = subprocess.run(["nm", "-A", "--defined-only", "-g", path],
                         capture_output=True, text=True, check=False).stdout
    names: set[str] = set()
    for line in out.splitlines():
        m = SYMBOL_RE.search(line)
        if not m:
            continue
        name = m.group(1)
        if name.startswith(("__imp_", "_imp__", "__")):
            continue
        name = re.sub(r"@\d+$", "", name)
        if not name or name.startswith("."):
            continue
        names.add(name.lower())
    return names


def build_table(libdir: str) -> dict[str, str]:
    owners: dict[str, list[str]] = {}
    for path in sorted(glob.glob(os.path.join(libdir, "lib*.a"))):
        stem = os.path.basename(path)[3:-2]
        low = stem.lower()
        if any(s in low for s in SKIP_SUBSTRINGS):
            continue
        for name in library_exports(path):
            owners.setdefault(name, [])
            if low not in owners[name]:
                owners[name].append(low)

    def rank(dll: str) -> tuple[int, str]:
        return (PRIORITY.index(dll) if dll in PRIORITY else len(PRIORITY), dll)

    return {name: sorted(dlls, key=rank)[0] for name, dlls in owners.items()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--libdir", default="/usr/i686-w64-mingw32/lib")
    ap.add_argument("--out", default="qiling/unpack/api_db.inc")
    args = ap.parse_args(argv)

    if not os.path.isdir(args.libdir):
        print(f"gen_api_db: {args.libdir} not found (install mingw-w64)", file=sys.stderr)
        return 1
    table = build_table(args.libdir)
    dlls = sorted({d for d in table.values()})
    with open(args.out, "w", encoding="ascii") as f:
        f.write("// GENERATED by tools/gen_api_db.py - do not edit by hand.\n")
        f.write("// Export-name -> owning-DLL table built from the host's mingw-w64\n")
        f.write("// import libraries (an SDK export database, not corpus ground truth).\n")
        f.write(f"// {len(table)} names, {len(dlls)} DLLs.\n")
        f.write("// clang-format off\n")
        f.write("static const char kApiDb[] =\n")
        for name in sorted(table):
            f.write(f'    "{name}\\t{table[name]}\\n"\n')
        f.write(";\n")
        f.write("// clang-format on\n")
    print(f"gen_api_db: {len(table)} names from {args.libdir} -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
