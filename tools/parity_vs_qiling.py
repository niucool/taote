#!/usr/bin/env python3
"""tools/parity_vs_qiling.py — the qiling-parity differential (PLAN_PARITY.md Phase 1.9).

Run the same PE, with the same settings, under the reference implementation
(`../qiling`, Python) and under taote, normalize both traces, and diff them:

    * the dispatch sequence (which API handlers fired, in which order)
    * the guest stdout
    * the exit code
    * the entry-point error class

Each side emits its own JSON trace (`tools/qiling_reference_runner.py`,
`build/tools/parity_trace`); this tool only orchestrates, normalizes, diffs and
clusters. Divergences are grouped by signature (``missing dispatch: _initterm``,
``extra dispatch: __acrt_iob_func``, ``stderr/exit/error``) so one root cause
shows up as one cluster instead of one finding per sample.

Preparation the reference needs (and taote does not): the Python qiling resolves
every import by mapping the *real* system DLL images out of
``<rootfs>/Windows/System32``. Those images only exist on a Windows host, so this
tool seeds a private rootfs with import stubs generated by ``tools/stub_dlls.py``
(one ``ret`` cell per exported name, export table naming it — the same shape
taote synthesizes in memory). Both emulators then dispatch the same API names at
the same kinds of slots, which is what makes the traces comparable.

Usage:
    tools/parity_vs_qiling.py                    # the starter corpus
    tools/parity_vs_qiling.py --sample FILE ...  # explicit samples
    tools/parity_vs_qiling.py --json out.json --report report.txt

Environment:
    QILING_REPO    the reference checkout            (default: ../qiling)
    QILING_PYTHON  a python with qiling's deps       (default: /tmp/qvenv/bin/python, then python3)
    QILING_ROOTFS  the reference rootfs tree         (default: $QILING_REPO/examples/rootfs)
"""

