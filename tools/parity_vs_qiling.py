def module_load_divergence(ref: Trace, ours: Trace):
    """The first LoadLibrary* whose answer differs (a module the harness can only
    synthesize, so the guest's downstream calls diverge for environment reasons).

    Returns the index in the reference's call list, or None.
    """

    positional = 0
    for i, (rcall, ocall) in enumerate(zip(ref.calls, ours.calls)):
        if rcall["name"] != ocall["name"]:
            break
        if rcall["name"].lower().startswith("loadlibrary") or rcall["name"].lower() in ("getmodulehandlea", "getmodulehandlew"):
            if retval_key(rcall["retval"]) != retval_key(ocall["retval"]):
                return i
            if is_pointerish(rcall["retval"]) and not is_pointerish(ocall["retval"]):
                return i
        positional += 1
    return None


def reference_timed_out(ref: Trace, ours: Trace):
    """True when the reference never finished, so its trace is not observable.

    A guest that spins - typically a network retry loop whose Sleep hook is a
    no-op in both emulators, so the loop never waits - costs the Python reference
    minutes of API dispatch and ends on the harness timeout, while taote finishes
    the same run in a second. There is nothing to diff against, and it is the
    reference's own cost, not a taote defect: the same sample alone in a quiet
    tree often completes. Recorded as a reference limitation, with the timeout
    named in the finding.
    """

    return ref.error_class == "timeout" and ours.error_class != "timeout"


def reference_lacks_handler(ref: Trace, ours: Trace, findings, extensions):
    """True when the reference cannot follow the guest past an import it lacks.

    The reference leaves an import it does not implement to the stub export cell
    - no dispatch record, no handler, and the guest sees whatever the return
    register happened to hold. taote implements a superset, so from the first
    such import onwards the two emulators are no longer running the same
    program: the reference's guest is following a path a real handler would
    never have taken. Everything the differ reports from that position on is
    downstream of the missing handler, not a taote defect - the reference's trace
    simply is not observable there. Distinct from `reference_limited`, which
    covers the case where the reference *faults* on the missing import: here it
    keeps going (often to its own exit 0) and the traces drift apart instead.
    """

    if not extensions:
        return False
    # a taote-side fault is never explained by a handler the reference lacks:
    # the guest that ran the real handler still crashed, which is a defect to
    # fix (PMA 14-02 keeps its EMU_ERR invalid_write this way)
    if ours.error_class is not None:
        return False
    # and the guest's *outcome* has to agree: a run that ends on a different
    # exit code took a different end state, which is a defect to chase rather
    # than a reference limitation to explain away
    if (ref.exit_code or 0) != (ours.exit_code or 0):
        return False
    for signature, _ in findings:
        if signature.startswith(("extra dispatch", "missing dispatch", "dispatch count", "stdout differs",
                                 "error class", "exit code", "first divergence")):
            continue
        return False
    our_seq = ours.sequence()
    first_ext = next((i for i, n in enumerate(our_seq) if n in extensions), None)
    if first_ext is None:
        return False
    for signature, detail in findings:
        match = re.search(r"from call #(\d+)", detail)
        if match is not None and int(match.group(1)) < first_ext:
            return False
    return True


def reference_faulted_alone(ref: Trace, ours: Trace, findings):
    """True when the only finding is the reference's own fault.

    taote reproduced the reference's dispatch sequence exactly - same calls, same
    order, same count, same return values, same stdout - and simply did not fault
    where the reference did. Nothing in the traces disagrees except the error
    class, so the fault is the reference's own limitation (PMA 12-01.dll_ and
    11-03.dll_: 68 identical dispatches, the reference dies on an unmapped fetch,
    taote exits 0).
    """

    if ref.error_class is None or ours.error_class is not None:
        return False
    if len(ref.calls) != len(ours.calls):
        return False
    if ref.sequence() != ours.sequence():
        return False
    return all(signature.startswith("error class") for signature, _ in findings)


def reference_limited(ref: Trace, ours: Trace, findings, extensions):
    """True when the divergence is the reference's own limitation.

    The reference leaves an import it does not implement to the stub cell (no
    dispatch, no return value), so its guest often walks off into unmapped
    memory right after - while taote, which does implement the import, keeps
    going. That shape is a reference limitation, not a taote defect, and it is
    recognisable without guessing: the reference faulted, taote did not, taote's
    extra dispatches are all imports the reference reports unimplemented, and
    nothing else in the trace disagrees.
    """

    if ref.error_class is None or ours.error_class is not None:
        return False
    if not extensions:
        # no unimplemented-import extension to explain it, so the only honest
        # reading is "the reference stopped before taote did": taote ran on
        # cleanly and every extra dispatch comes at or after the reference's
        # last one. A taote that faulted is never excused this way.
        if ours.exit_code != 0:
            return False
        for signature, detail in findings:
            if signature.startswith(
                    ("extra dispatch", "dispatch count", "error class", "exit code", "first divergence")):
                continue
            return False
        for signature, detail in findings:
            if not signature.startswith("extra dispatch"):
                continue
            match = re.search(r"from call #(\d+)", detail)
            if match is None or int(match.group(1)) < len(ref.calls):
                return False
        return True
    for signature, _ in findings:
        if signature.startswith(("extra dispatch", "dispatch count", "error class", "exit code", "first divergence")):
            continue
        return False
    our_seq = ours.sequence()
    # the first call that is an import the reference leaves unimplemented: from
    # there on, taote is executing code the reference never ran, so a later
    # extra dispatch is downstream of the same limitation, not a new defect
    first_ext = next((i for i, n in enumerate(our_seq) if n in extensions), None)
    if first_ext is None:
        return False
    for signature, detail in findings:
        if not signature.startswith("extra dispatch"):
            continue
        name = signature.split(": ", 1)[1]
        if name in extensions:
            continue
        match = re.search(r"from call #(\d+)", detail)
        if match is None or int(match.group(1)) < first_ext:
            return False
    return True


def diff_traces(ref: Trace, ours: Trace):
    """Return (findings, clusters) where each finding names one divergence."""

    findings = []

    # a module the harness could only synthesize answers a different base (or no
    # base at all) on one side; everything the guest does with that handle
    # differs for reasons that are not handler semantics, so it is classified
    # as an environment divergence instead of chased
    env_index = module_load_divergence(ref, ours)
    if env_index is not None:
        r = ref.calls[env_index]
        o = ours.calls[env_index]
        findings.append(
            (
                "environment: module load differs",
                f"call #{env_index}: reference {r['name']} -> {r['retval']!r}, taote -> {o['retval']!r} "
                f"(the harness can only synthesize an image with a different export set)",
            )
        )
        return findings, {"environment": [findings[0][1]]}

    ref_seq, our_seq = ref.sequence(), ours.sequence()
    if ref_seq != our_seq:
        # align positionally and stop at the first divergence; the rest of the
        # report is noise until that one is fixed
        limit = min(len(ref_seq), len(our_seq))
        first = limit
        for i in range(limit):
            if ref_seq[i] != our_seq[i]:
                first = i
                break
        missing = [n for n in ref_seq[first:] if n not in our_seq[first:]]
        extra = [n for n in our_seq[first:] if n not in ref_seq[first:]]
        for name in dict.fromkeys(missing):
            findings.append((f"missing dispatch: {name}", f"reference dispatched {name}, taote did not (from call #{first})"))
        for name in dict.fromkeys(extra):
            if name in ref.unimplemented:
                # taote answers an import the reference leaves to the stub cell
                continue
            findings.append((f"extra dispatch: {name}", f"taote dispatched {name}, the reference did not (from call #{first})"))
        if not missing and not extra:
            findings.append(
                (
                    "dispatch order differs",
                    f"same APIs, different order from #{first}: reference {ref_seq[first:first + 5]}, taote {our_seq[first:first + 5]}",
                )
            )
        # the call where the two runs parted company: the earliest point where
        # either the name or the return value differs. That value difference is
        # usually the root cause of everything downstream (a guest branching on
        # it takes a different path, so the rest of the trace mismatches).
        for i in range(min(len(ref_seq), len(our_seq))):
            if ref.calls[i]["name"] == ours.calls[i]["name"] and \
               retval_key(ref.calls[i]["retval"]) != retval_key(ours.calls[i]["retval"]):
                findings.insert(
                    0,
                    (
                        f"first divergence: {ref.calls[i]['name']} return value",
                        f"call #{i}: reference {ref.calls[i]['retval']!r}, taote {ours.calls[i]['retval']!r} "
                        f"(everything after this point differs because the guest branched on it)",
                    ),
                )
                break

        extensions = sum(1 for n in our_seq if n in ref.unimplemented)
        if len(ref_seq) + extensions < len(our_seq) or len(ref_seq) > len(our_seq):
            findings.append(
                (
                    "dispatch count differs",
                    f"reference {len(ref_seq)} calls, taote {len(our_seq)} calls "
                    f"({extensions} of taote's are imports the reference does not implement)",
                )
            )
    else:
        # same sequence: compare the per-call return values
        for i, (r, o) in enumerate(zip(ref.calls, ours.calls)):
            if retval_key(r["retval"]) != retval_key(o["retval"]):
                findings.append(
                    (
                        f"return value differs: {r['name']}",
                        f"call #{i}: reference {r['retval']!r}, taote {o['retval']!r}",
                    )
                )

    if ref.stdout != ours.stdout:
        ref_lines = ref.stdout.splitlines()
        our_lines = ours.stdout.splitlines()
        detail = f"reference {ref_lines[:4]!r}, taote {our_lines[:4]!r}"
        findings.append(("stdout differs", detail))

    if ref.error_class != ours.error_class:
        findings.append(
            (
                f"error class differs: {ref.error_class or 'none'} vs {ours.error_class or 'none'}",
                f"reference error {ref.error!r}, taote error {ours.error!r}",
            )
        )

    ref_exit = ref.exit_code if ref.exit_code is not None else 0
    our_exit = ours.exit_code if ours.exit_code is not None else 0
    # The reference leaves `ql.os.exit_code` at 0 when a run dies on a unicorn
    # fault (it only records the error), while taote sets the guest's
    # STATUS_ACCESS_VIOLATION (PLAN_PARITY Phase 1.5, a deliberate delta), so the
    # exit code is only comparable when neither side faulted.
    faulted = ref.error_class is not None and ours.error_class is not None
    if not faulted and (ref_exit & 0xFFFFFFFF) != (our_exit & 0xFFFFFFFF):
        findings.append(("exit code differs", f"reference {ref_exit}, taote {our_exit}"))

    clusters = {}
    for signature, detail in findings:
        clusters.setdefault(signature.split(":")[0] if signature.count(":") and not signature.startswith("error class") else signature, []).append(detail)
    return findings, clusters


