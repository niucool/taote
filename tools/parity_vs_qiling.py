def find_python(explicit=None):
    candidates = [explicit, os.environ.get("QILING_PYTHON"), "/tmp/qvenv/bin/python", sys.executable]
    for cand in candidates:
        if not cand:
            continue
        try:
            probe = subprocess.run([cand, "-c", "import unicorn, capstone, pefile"], capture_output=True)
        except OSError:
            continue
        if probe.returncode == 0:
            return cand
    return None


def run_json(cmd, timeout):
    try:
        # the traces are JSON, but a guest's stdout rides inside them and a
        # sample can print bytes that are not valid utf-8 (a packed sample's
        # decoy strings), so decode permissively rather than crashing the sweep
        proc = subprocess.run(cmd, capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None, "timeout"
    out = proc.stdout.decode("utf-8", errors="replace")
    err = proc.stderr.decode("utf-8", errors="replace")
    text = out.strip()
    if not text:
        return None, (err.strip().splitlines() or ["no output"])[-1]
    try:
        return json.loads(text), None
    except json.JSONDecodeError as ex:
        return None, f"unparsable trace: {ex}"


def prepare_rootfs(rootfs_src: Path, work: Path, samples, machine: str):
    """Seed a private rootfs: the reference's tree + registry hives + stub dlls."""

    dst = work / f"rootfs_{machine}"
    if dst.exists():
        shutil.rmtree(dst)
    system32 = dst / "Windows" / "System32"
    system32.mkdir(parents=True, exist_ok=True)
    for sub in ("Windows/registry", "qltest"):
        (dst / sub).mkdir(parents=True, exist_ok=True)

    if rootfs_src and rootfs_src.exists():
        for entry in rootfs_src.iterdir():
            if entry.name in ("bin", "Windows"):
                continue
            target = dst / entry.name
            if entry.is_dir():
                shutil.copytree(entry, target, dirs_exist_ok=True)
            else:
                shutil.copy2(entry, target)

    # the registry hives: the reference refuses to start a PE without them. The
    # full hives are not publicly distributable, and neither emulator reads
    # anything but "key not found" from an empty hive, so a valid minimal hive
    # (a single root key, no subkeys) is enough for a differential run.
    make_hive = HERE / "mkreg_hive.py"
    if make_hive.exists():
        subprocess.run([sys.executable, str(make_hive), str(dst / "Windows" / "registry")], check=True, capture_output=True)

    cmd = [sys.executable, str(HERE / "stub_dlls.py"), "--out", str(system32), "--machine", machine]
    cmd += ["--from-pe", *[str(s) for s in samples]]
    subprocess.run(cmd, check=True, capture_output=True)

    # the reference maps guest paths against the rootfs: a sample living outside
    # it raises `'<path>' is not in the subpath of '<rootfs>'` from its own path
    # mapper, which reads like an emulation fault. Stage every sample inside.
    for sample in samples:
        target = dst / "Windows" / sample.name
        if not target.exists():
            shutil.copy2(sample, target)
    return dst


def run_one(sample: Path, machine: str, rootfs: Path, argv, qiling_python, qiling_repo, taote_trace, work: Path, timeout, count,
            ref_sample=None):
    """Run both emulators on one sample and return (ref_raw, taote_raw)."""

    ref_json = work / (sample.name + ".qiling.json")
    our_json = work / (sample.name + ".taote.json")

    ref_cmd = [
        qiling_python,
        str(HERE / "qiling_reference_runner.py"),
        "--qiling",
        str(qiling_repo),
        "--sample",
        str(ref_sample or sample),
        "--rootfs",
        str(rootfs),
        "--out",
        str(ref_json),
    ]
    if argv:
        ref_cmd += ["--argv", *argv]
    if count:
        # the same deterministic instruction budget taote gets: a guest that
        # spins (a retry loop whose Sleep hook is a no-op on both sides) must
        # stop on both sides, or the reference only ever ends on the timeout
        ref_cmd += ["--count", str(count)]
    ref_raw, ref_err = run_json(ref_cmd, timeout)
    if ref_raw is None and ref_err == "timeout":
        # a timed-out reference run is usually host load, not the sample: one
        # retry with a longer budget, so a measurement does not flip on it
        seen, ref_raw = ref_err, None
        ref_raw, ref_err = run_json(ref_cmd, timeout * 2)
        if ref_raw is None:
            ref_err = seen
    if ref_raw is None and ref_json.exists():
        # a guest's stdout rides in the trace and can be non-utf-8 (see
        # run_json), so the fallback read decodes permissively too
        ref_raw, ref_err = json.loads(ref_json.read_text(encoding="utf-8", errors="replace")), None
    if ref_raw is None:
        ref_raw = {"emulator": "qiling", "sample": sample.name, "apis": [], "stdout": "", "error": ref_err, "exit_code": None}

    # both emulators run the *same* staged tree: the stub dll export sets and the
    # paths the guest resolves have to be identical or a GetProcAddress answer
    # differs for harness reasons (PMA 01-02 asked for an export only the
    # corpus-union rootfs carried)
    our_cmd = [str(taote_trace), str(ref_sample or sample), "--rootfs", str(rootfs),
               "--out", str(our_json)]
    if argv:
        our_cmd += ["--argv", *argv]
    if count:
        our_cmd += ["--count", str(count)]
    our_raw, our_err = run_json(our_cmd, timeout)
    if our_raw is None and our_json.exists():
        our_raw, our_err = json.loads(our_json.read_text(encoding="utf-8", errors="replace")), None
    if our_raw is None:
        our_raw = {"emulator": "taote", "sample": sample.name, "apis": [], "stdout": "", "error": our_err, "exit_code": None}

    return ref_raw, our_raw


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="the qiling-parity differential")
    ap.add_argument("--sample", action="append", default=[], help="a sample to compare (repeatable)")
    ap.add_argument("--corpus", default=None, help="directory of samples to compare (default: the starter corpus)")
    ap.add_argument("--qiling-repo", default=os.environ.get("QILING_REPO", str(REPO.parent / "qiling")))
    ap.add_argument("--qiling-python", default=None)
    ap.add_argument("--rootfs", default=None, help="the reference rootfs tree (default: $QILING_REPO/examples/rootfs)")
    ap.add_argument("--taote-trace", default=str(REPO / "build" / "tools" / "parity_trace"))
    ap.add_argument("--argv", nargs="*", default=[])
    ap.add_argument("--count", type=int, default=40000000, help="deterministic instruction budget")
    ap.add_argument("--timeout", type=int, default=120, help="seconds per run")
    ap.add_argument("--json", default=None, help="write the machine-readable report here")
    ap.add_argument("--report", default=None, help="write the human-readable report here")
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--require-match", type=int, default=0,
                    help="exit non-zero unless at least N samples match (the ctest smoke gate)")
    ap.add_argument("--work", default=None, help="keep the per-run artifacts here (default: a temp dir)")
    args = ap.parse_args(argv)

    qiling_repo = Path(args.qiling_repo).resolve()
    if not (qiling_repo / "qiling").is_dir():
        print(f"parity: no reference checkout at {qiling_repo} (set QILING_REPO)", file=sys.stderr)
        return 77

    qiling_python = find_python(args.qiling_python)
    if qiling_python is None:
        print("parity: no python with unicorn/capstone/pefile found (set QILING_PYTHON)", file=sys.stderr)
        return 77

    taote_trace = Path(args.taote_trace)
    if not taote_trace.exists():
        print(f"parity: build the taote side first: cmake --build build --target parity_trace ({taote_trace})", file=sys.stderr)
        return 77

    samples = [Path(s).resolve() for s in args.sample]
    if args.corpus:
        corpus = Path(args.corpus)
        samples += sorted(p for p in corpus.iterdir() if p.suffix.lower() in (".exe", ".dll", ".sys", ".exe_", ".dll_", ".sys_"))
    if not samples:
        base = Path(os.environ.get("TAOTE_BINS", REPO / "tests" / "data" / "pegasus"))
        samples = [base / name for name in STARTER if (base / name).exists()]
    if not samples:
        print("parity: no samples to compare", file=sys.stderr)
        return 77

    rootfs_src = Path(args.rootfs) if args.rootfs else qiling_repo / "examples" / "rootfs"
    work = Path(args.work) if args.work else Path(tempfile.mkdtemp(prefix="taote_parity_"))
    work.mkdir(parents=True, exist_ok=True)

    # one rootfs per machine type: the stub export sets are the union over the
    # samples, so a single seed serves the whole run
    rootfs_by_machine = {}
    for machine in ("x86", "x64"):
        machine_samples = [s for s in samples if _machine_of(s) == machine]
        if not machine_samples:
            continue
        src = rootfs_src / ("x86_windows" if machine == "x86" else "x8664_windows")
        rootfs_by_machine[machine] = prepare_rootfs(src, work, machine_samples, machine)

    results = []
    for sample in samples:
        machine = _machine_of(sample)
        rootfs = rootfs_by_machine.get(machine)
        if rootfs is None:
            results.append({"sample": sample.name, "verdict": "skipped", "reason": f"unsupported machine for {sample.name}"})
            continue
        ref_sample = (rootfs / "Windows" / sample.name) if rootfs is not None else sample
        ref_raw, our_raw = run_one(
            sample,
            machine,
            rootfs,
            args.argv,
            qiling_python,
            qiling_repo,
            taote_trace,
            work,
            args.timeout,
            args.count,
            ref_sample=ref_sample,
        )
        ref = Trace(ref_raw, rootfs_sample_path=ref_sample)
        ours = Trace(our_raw)
        findings, clusters = diff_traces(ref, ours)
        extensions = sorted(n for n in ours.sequence() if n in ref.unimplemented)
        results.append(
            {
                "sample": sample.name,
                "verdict": ("match" if not findings else
                            "environment" if any(sig.startswith("environment") for sig, _ in findings) else
                            "reference_limit" if (reference_timed_out(ref, ours) or
                                                  reference_faulted_alone(ref, ours, findings) or
                                                  reference_limited(ref, ours, findings, extensions) or
                                                  reference_lacks_handler(ref, ours, findings, extensions)) else
                            "diverged"),
                "taote_extensions": extensions,
                "reference": {"calls": len(ref.calls), "exit": ref.exit_code, "error": ref.error },
                "taote": {"calls": len(ours.calls), "exit": ours.exit_code, "error": ours.error, "error_types": our_raw.get("error_types")},
                "findings": [{"signature": s, "detail": d} for s, d in findings],
                "clusters": {k: v for k, v in clusters.items()},
            }
        )

    report = {
        "reference": {"repo": str(qiling_repo), "python": qiling_python},
        "samples": results,
        "summary": {
            "total": len(results),
            "match": sum(1 for r in results if r["verdict"] == "match"),
            "diverged": sum(1 for r in results if r["verdict"] == "diverged"),
            "environment": sum(1 for r in results if r["verdict"] == "environment"),
            "reference_limit": sum(1 for r in results if r["verdict"] == "reference_limit"),
            "cluster_counts": _cluster_counts(results),
        },
    }

    text = render(report)
    if args.report:
        Path(args.report).write_text(text)
    if args.json:
        Path(args.json).write_text(json.dumps(report, indent=2))
    if not args.quiet:
        print(text)

    # a divergence is a finding to report, not a harness failure - unless the
    # caller asked for a match floor (the ctest smoke gate)
    if args.require_match and report["summary"]["match"] < args.require_match:
        return 1
    return 0


def _machine_of(sample: Path) -> str:
    """PE machine type from the COFF header (32- vs 64-bit)."""

    try:
        with open(sample, "rb") as f:
            header = f.read(0x200)
        if header[:2] != b"MZ":
            return "unknown"
        offset = int.from_bytes(header[0x3C:0x40], "little")
        if offset + 6 > len(header):
            with open(sample, "rb") as f:
                f.seek(offset)
                machine = int.from_bytes(f.read(6)[4:6], "little")
        else:
            machine = int.from_bytes(header[offset + 4:offset + 6], "little")
        return "x64" if machine == 0x8664 else "x86"
    except OSError:
        return "unknown"


def _cluster_counts(results):
    counts = {}
    for result in results:
        for signature in result.get("clusters") or {}:
            counts[signature] = counts.get(signature, 0) + 1
    return dict(sorted(counts.items(), key=lambda kv: -kv[1]))


def render(report) -> str:
    lines = []
    lines.append("qiling-parity differential (PLAN_PARITY.md Phase 1.9)")
    lines.append(f"reference: {report['reference']['repo']} ({report['reference']['python']})")
    lines.append("")
    summary = report["summary"]
    lines.append(
        f"samples: {summary['total']}  match: {summary['match']}  "
        f"environment: {summary.get('environment', 0)}  "
        f"reference_limit: {summary.get('reference_limit', 0)}  diverged: {summary['diverged']}"
    )
    lines.append("")
    for result in report["samples"]:
        if result["verdict"] == "skipped":
            lines.append(f"[skip] {result['sample']}: {result.get('reason')}")
            continue
        mark = {"match": "ok  ", "environment": "env ", "reference_limit": "refl", "diverged": "DIFF"}.get(result["verdict"], "DIFF")
        ref, ours = result["reference"], result["taote"]
        lines.append(
            f"[{mark}] {result['sample']}: reference {ref['calls']} calls exit {ref['exit']} "
            f"{'(error: ' + str(ref['error']) + ')' if ref['error'] else ''} | "
            f"taote {ours['calls']} calls exit {ours['exit']} "
            f"{'(error: ' + str(ours['error']) + ')' if ours['error'] else ''}"
        )
        if result.get("taote_extensions"):
            names = sorted(set(result["taote_extensions"]))
            lines.append(f"        + taote extends the reference with {len(names)} handler(s) the reference does not implement: {', '.join(names)}")
        for finding in result["findings"]:
            lines.append(f"        - {finding['signature']}: {finding['detail']}")
    if summary["cluster_counts"]:
        lines.append("")
        lines.append("root-cause clusters (signature -> samples):")
        for signature, count in summary["cluster_counts"].items():
            lines.append(f"  {count:3d}  {signature}")
    return "\n".join(lines) + "\n"


