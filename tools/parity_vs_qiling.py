_ERROR_CLASSES = (
    ("invalid memory fetch", "invalid_fetch"),
    ("fetch from non-executable", "invalid_fetch"),
    ("failed to fetch", "invalid_fetch"),
    ("invalid memory read", "invalid_read"),
    ("invalid memory write", "invalid_write"),
    ("invalid memory access", "invalid_access"),
    ("non-executable memory", "invalid_fetch"),
    ("invalid instruction", "invalid_insn"),
    ("unsupported api", "unsupported_api"),
    ("max api count", "max_api_count"),
    ("timeout", "timeout"),
    ("unhandled cpu exception", "invalid_cpu_exception"),
    ("invalid cpu exception", "invalid_cpu_exception"),
)


def classify(text):
    """Map either side's raw error text onto one error vocabulary."""

    if not text:
        return None
    low = str(text).lower()
    for needle, kind in _ERROR_CLASSES:
        if needle in low:
            return kind
    return "emu_error"


def is_pointerish(value):
    """A return value in the guest's address space (never byte-equal across emulators)."""

    return value is not None and value > 0x10000


def normalize_addr(addr, image_base):
    if addr is None:
        return None
    if image_base and image_base <= addr < image_base + 0x4000000:
        return f"sample+{addr - image_base:#x}"
    return f"{addr:#x}"


class Trace:
    """One emulator's normalized view of a run."""

    def __init__(self, raw, rootfs_sample_path=None):
        self.raw = raw
        self.sample = raw.get("sample")
        base = raw.get("image_base")
        self.image_base = base if isinstance(base, int) else None
        self.exit_code = raw.get("exit_code")
        self.ran = bool(raw.get("ran", raw.get("error") is None))
        self.error = raw.get("error")
        self.error_class = classify(self.error)
        self.stderr = raw.get("traceback")

        stdout = raw.get("stdout") or ""
        # the guest prints argv[0], which is the *rootfs* copy of the sample and
        # differs per side and per run: fold any path ending in the sample name
        if self.sample:
            stdout = re.sub(r"[^\s'\"]*[/\\]" + re.escape(self.sample), f"<{self.sample}>", stdout)
        if rootfs_sample_path:
            stdout = stdout.replace(str(rootfs_sample_path), f"<{self.sample}>")
        stdout = stdout.replace("\r\n", "\n")
        self.stdout = stdout

        self.strings = set(raw.get("strings") or [])
        # the reference's own "api X is not implemented" warnings: a dispatch
        # taote makes where the reference has no handler is an extension, not a
        # divergence (taote's handler surface is a superset)
        self.unimplemented = set(raw.get("unimplemented") or [])

        self.calls = []
        for record in raw.get("apis") or []:
            self.calls.append(
                {
                    "name": record.get("name"),
                    "retval": record.get("retval"),
                    "retaddr": normalize_addr(record.get("retaddr"), self.image_base),
                    "address": normalize_addr(record.get("address"), self.image_base),
                }
            )

    def sequence(self):
        return [c["name"] for c in self.calls]


def retval_key(value):
    """Normalize a return value for comparison (pointers only compare as null/non-null).

    A negative return value is the signed reading of the same bit pattern the
    other side reports unsigned (the reference's Python ints keep the handler's
    -1 while taote's C++ returns 0xffffffffffffffff), so both fold to the
    two's-complement 64-bit value before comparing.
    """

    if value is None:
        return "null"
    if isinstance(value, bool):
        value = int(value)
    if isinstance(value, int) and value < 0:
        value &= 0xFFFFFFFFFFFFFFFF
    if is_pointerish(value):
        return "ptr"
    return str(value)


