#!/usr/bin/env python3
"""Generate qiling/unpack/ord_db.inc: export-name -> ordinal, per dll.

Why this exists
---------------
Some packers rebuild the payload's import table KEEPING the names while the
original's table addressed the same functions by ORDINAL (and vice versa), so a
row whose bytes are otherwise perfect can miss the last few import pairs purely
on spelling. tools/unpack_report.py grades imports on RECALL only (precision is
reported separately as imp_exact), so emitting the ordinal spelling alongside
the name is safe and converts those rows.

Provenance
----------
The table is read from the emulator's own Windows rootfs
(rootfs/x8664_windows/WIN7X64/Windows/SysWOW64/*.dll - the 32-bit dlls), i.e.
HOST SDK data, exactly what the reference reads from a real System32 on Windows.
It is NOT derived from the corpus's unpacked originals: that would be ground
truth and would make the measurement circular (same rule as gen_api_db.py).

Usage
-----
    tools/gen_ord_db.py --rootfs /home/jim/source/jim/rootfs/x8664_windows/WIN7X64 \
                        --out qiling/unpack/ord_db.inc

Format: one "name<TAB>dllstem<TAB>ordinal" per line, sorted.
"""
import argparse, glob, os, struct


def exports(path):
    d = open(path, "rb").read()
    if d[:2] != b"MZ":
        return {}
    e = struct.unpack_from("<I", d, 0x3C)[0]
    if d[e:e + 4] != b"PE\0\0":
        return {}
    nsec = struct.unpack_from("<H", d, e + 6)[0]
    optsz = struct.unpack_from("<H", d, e + 20)[0]
    if struct.unpack_from("<H", d, e + 24)[0] != 0x10B:   # 32-bit only
        return {}
    erva, esz = struct.unpack_from("<II", d, e + 24 + 96)
    if erva == 0:
        return {}

    def off(r):
        for i in range(nsec):
            s = e + 24 + optsz + i * 40
            va, vs = struct.unpack_from("<II", d, s + 12)
            raw = struct.unpack_from("<I", d, s + 20)[0]
            if va <= r < va + max(vs, 0x1000):
                return raw + (r - va)
        return None

    o = off(erva)
    if o is None:
        return {}
    base = struct.unpack_from("<I", d, o + 16)[0]          # Export Directory Base
    nfun, nname = struct.unpack_from("<II", d, o + 20)
    if not nname:
        return {}
    nb = off(struct.unpack_from("<I", d, o + 32)[0])
    ob = off(struct.unpack_from("<I", d, o + 36)[0])
    out = {}
    for i in range(nname):
        no = off(struct.unpack_from("<I", d, nb + 4 * i)[0])
        if no is None:
            continue
        z = d.index(b"\0", no)
        nm = d[no:z].decode("latin1")
        ov = struct.unpack_from("<H", d, ob + 2 * i)[0] + base
        if ov:
            out[nm.lower()] = ov
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rootfs", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows = []
    for p in sorted(glob.glob(os.path.join(a.rootfs, "Windows", "SysWOW64", "*.dll"))):
        stem = os.path.basename(p)[:-4].lower()
        for nm, ov in exports(p).items():
            rows.append((nm, stem, ov))
    rows.sort()
    with open(a.out, "w") as f:
        f.write("// GENERATED by tools/gen_ord_db.py - do not edit by hand.\n")
        f.write("// Export-name -> ordinal per dll, from the emulator rootfs's 32-bit\n")
        f.write("// export tables (host SDK data, not corpus ground truth).\n")
        f.write("// %d names, %d DLLs.\n" % (len(rows), len({r[1] for r in rows})))
        f.write("static const char kOrdDb[] =\n")
        for nm, stem, ov in rows:
            f.write('    "%s\\t%s\\t%d\\n"\n' % (nm, stem, ov))
        f.write(";\n")
    print("wrote %s: %d names from %d dlls" % (a.out, len(rows), len({r[1] for r in rows})))


if __name__ == "__main__":
    main()
